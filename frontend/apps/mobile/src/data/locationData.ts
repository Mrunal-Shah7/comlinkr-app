const STATE_TO_COUNTRY: Record<string, string> = Object.entries(STATES_BY_COUNTRY).reduce(
  (acc, [country, states]) => {
    for (const state of states) acc[state] = country;
    return acc;
  },
  {} as Record<string, string>,
);

const CITY_TO_STATE: Record<string, string> = Object.entries(CITIES_BY_STATE).reduce(
  (acc, [state, cities]) => {
    for (const city of cities) if (!(city in acc)) acc[city] = state;
    return acc;
  },
  {} as Record<string, string>,
);

/** Reverse lookup for a guest-picked city (which has no country/state of its own). */
export function resolveCityLocation(city: string): { state: string | null; country: string | null } {
  const state = CITY_TO_STATE[city] ?? null;
  const country = state ? (STATE_TO_COUNTRY[state] ?? null) : null;
  return { state, country };
}
